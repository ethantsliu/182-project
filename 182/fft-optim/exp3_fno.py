"""Experiment 3: per-mode Muon / Shampoo / SOAP for dense Fourier Neural Operators.

Each spectral weight is stored as (K, Cin, Cout) complex: one matrix W_k per kept mode (2D: both kx corners
x ky modes, flattened). The new optimizers touch only these; lifting/projection/1x1 layers use AdamW.
  mode_muon      complex polar factor of each mode's Nesterov momentum
  mode_shampoo   L_k^-1/4 M_k R_k^-1/4, grafted to Adam's norm
  mode_soap      Adam in each mode's eigenbasis
  muon_flat      Muon on the flattened (Cin, K*Cout) weight
  soap_flat      SOAP on the flattened weight (column-blocked to <= 1152)
  shampoo_shared one Shampoo pair (L = sum_k G_k G_k^H, R = sum_k G_k^H G_k) shared across modes
  adamw          AdamW (complex = independent real/imag)
kill: AdamW on Burgers; accumulate L_k over the last 500 steps; GO for the Shampoo variants if the median
      cond(L_k) > 10, else only mode_muon (+ its controls) go to the main run.
main: Burgers, Darcy, 2D Navier-Stokes (generated by prep_data.py), relative L2 test error vs steps.
"""
import json
import math
import os
import statistics
import sys
import time

import torch
import torch.nn as nn
import torch.nn.functional as F

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from fftopt.core import MatrixOpt, View, blocked_flat_view, eig_condition, nbytes_state, warmup_linear  # noqa: E402
from fftopt import pool  # noqa: E402

OUT = os.environ.get("FFT_OUT", os.path.join(os.path.dirname(os.path.abspath(__file__)), "runs"))
SMOKE = os.environ.get("SMOKE") == "1"
DATA = os.path.join(os.environ.get("FFT_DATA", "/mnt/work/dev_patel/data"), "fno")
DECAY = 1e-5


class Spectral1d(nn.Module):
    def __init__(self, ci, co, K):
        super().__init__()
        self.K = K
        self.w = nn.Parameter(torch.randn(K, ci, co, dtype=torch.cfloat) / (ci * co) ** 0.5)

    def forward(self, x):  # (B, C, N)
        xf = torch.fft.rfft(x, norm="ortho")
        out = torch.zeros(x.shape[0], self.w.shape[2], xf.shape[-1], dtype=torch.cfloat, device=x.device)
        out[..., :self.K] = torch.einsum("bik,kio->bok", xf[..., :self.K], self.w)
        return torch.fft.irfft(out, n=x.shape[-1], norm="ortho")


class Spectral2d(nn.Module):
    def __init__(self, ci, co, K):
        super().__init__()
        self.K = K
        self.w = nn.Parameter(torch.randn(2 * K * K, ci, co, dtype=torch.cfloat) / (ci * co) ** 0.5)

    def forward(self, x):  # (B, C, H, W)
        B, _, H, W = x.shape
        K = self.K
        xf = torch.fft.rfft2(x, norm="ortho")
        w = self.w.reshape(2, K, K, *self.w.shape[1:])
        out = torch.zeros(B, self.w.shape[2], H, W // 2 + 1, dtype=torch.cfloat, device=x.device)
        out[:, :, :K, :K] = torch.einsum("bixy,xyio->boxy", xf[:, :, :K, :K], w[0])
        out[:, :, -K:, :K] = torch.einsum("bixy,xyio->boxy", xf[:, :, -K:, :K], w[1])
        return torch.fft.irfft2(out, s=(H, W), norm="ortho")


class FNO(nn.Module):
    def __init__(self, dim, cin, width, K, layers=4):
        super().__init__()
        self.dim = dim
        conv = nn.Conv1d if dim == 1 else nn.Conv2d
        self.lift = conv(cin + dim, width, 1)
        self.spec = nn.ModuleList((Spectral1d if dim == 1 else Spectral2d)(width, width, K) for _ in range(layers))
        self.pw = nn.ModuleList(conv(width, width, 1) for _ in range(layers))
        self.proj = nn.Sequential(conv(width, 128, 1), nn.GELU(), conv(128, 1, 1))

    def forward(self, x):  # x (B, 1, *grid)
        grids = [torch.linspace(0, 1, n, device=x.device) for n in x.shape[2:]]
        mesh = torch.meshgrid(*grids, indexing="ij")
        g = torch.stack(mesh)[None].expand(x.shape[0], -1, *x.shape[2:])
        h = self.lift(torch.cat([x, g], 1))
        for i, (s, p) in enumerate(zip(self.spec, self.pw)):
            h = s(h) + p(h)
            if i < len(self.spec) - 1:
                h = F.gelu(h)
        return self.proj(h)


CFG = {  # dim, width, modes, epochs, batch
    "burgers": (1, 64, 16, 100, 20),
    "darcy": (2, 32, 12, 100, 20),
    "ns": (2, 32, 12, 100, 20),
}

ARMS = {  # name: (mode, view, center lr)
    "adamw": ("adamw", None, 1e-3),
    "mode_muon": ("muon", "modes", 0.02),
    "mode_shampoo": ("shampoo", "modes", 1e-3),
    "mode_soap": ("soap", "modes", 3e-3),
    "muon_flat": ("muon", "flat", 0.02),
    "soap_flat": ("soap", "flat_blocked", 3e-3),
    "shampoo_shared": ("shampoo_shared", "modes", 1e-3),
}
SHAMPOO_ARMS = {"mode_shampoo", "mode_soap", "soap_flat", "shampoo_shared"}


def flat(shape, blocked):
    K, ci, co = shape
    fl = lambda x: x.permute(1, 0, 2).reshape(ci, K * co)
    un = lambda X: X.reshape(ci, K, co).permute(1, 0, 2)
    if blocked:
        return blocked_flat_view(shape, 1152, fl, un)
    return View(lambda x: fl(x)[None], lambda Y: un(Y[0]))


def make_opt(arm, params, lr):
    mode, view, _ = ARMS[arm]
    if mode == "adamw":
        return torch.optim.AdamW(params, lr=lr, weight_decay=DECAY / lr)
    groups = []
    for p in params:
        v = View(lambda x: x, lambda Y: Y) if view == "modes" else flat(p.shape, view == "flat_blocked")
        groups.append(dict(params=[p], view=v))
    return MatrixOpt(groups, lr=lr, mode=mode, decay=DECAY, precond_every=10)


def set_mult(opts, mult):
    for o in opts:
        for g in o.param_groups:
            g.setdefault("base_lr", g["lr"])
            if "lr_mult" in g:
                g["lr_mult"] = mult
            else:
                g["lr"] = g["base_lr"] * mult


def rel_l2(pred, y):
    return ((pred - y).flatten(1).norm(dim=1) / y.flatten(1).norm(dim=1))


def train(a, collect=None):
    torch.manual_seed(a["seed"])
    dev = "cuda"
    d = torch.load(os.path.join(DATA, f"{a['dataset']}.pt"))
    dim, width, K, epochs, bs = CFG[a["dataset"]]
    if SMOKE:
        epochs = 3
    xtr, ytr = d["x_train"].to(dev)[:, None], d["y_train"].to(dev)[:, None]
    xte, yte = d["x_test"].to(dev)[:, None], d["y_test"].to(dev)[:, None]
    mu, sd = xtr.mean(), xtr.std()
    xtr, xte = (xtr - mu) / sd, (xte - mu) / sd
    ymu, ysd = ytr.mean(), ytr.std()
    model = FNO(dim, 1, width, K).to(dev)
    spec = [s.w for s in model.spec]
    sid = {id(p) for p in spec}
    rest = [p for p in model.parameters() if id(p) not in sid]
    topt = make_opt(a["arm"], spec, a["lr"])
    ropt = torch.optim.AdamW(rest, lr=1e-3, weight_decay=1e-4)
    spe = xtr.shape[0] // bs
    total, step, ttrain, curve, diverged = spe * epochs, 0, 0.0, [], False

    def evaluate():
        model.eval()
        with torch.no_grad():
            e = torch.cat([rel_l2(model(xte[i:i + 100]) * ysd + ymu, yte[i:i + 100]) for i in range(0, xte.shape[0], 100)])
        model.train()
        return e.mean().item()

    eval_every = max(1, epochs // 20)
    for ep in range(epochs):
        perm = torch.randperm(xtr.shape[0], device=dev)
        torch.cuda.synchronize()
        t0 = time.time()
        for i in range(spe):
            idx = perm[i * bs:(i + 1) * bs]
            set_mult([topt, ropt], warmup_linear(step, total))
            pred = model(xtr[idx]) * ysd + ymu
            loss = rel_l2(pred, ytr[idx]).mean()
            topt.zero_grad(set_to_none=True)
            ropt.zero_grad(set_to_none=True)
            loss.backward()
            if collect is not None:
                collect(spec, step, total)
            topt.step()
            ropt.step()
            step += 1
        torch.cuda.synchronize()
        ttrain += time.time() - t0
        if not math.isfinite(loss.item()):
            diverged = True
            break
        if (ep + 1) % eval_every == 0 or ep == epochs - 1:
            curve.append([step, evaluate()])
    return dict(final=None if diverged else curve[-1][1], curve=curve, steps=step,
                ms_per_step=1000 * ttrain / max(step, 1), opt_state_mb=nbytes_state(topt) / 2 ** 20)


def job(a):
    json.dump({**a, **train(a)}, open(a["out"], "w"))


def kill():
    d = os.path.join(OUT, "exp3_kill")
    os.makedirs(d, exist_ok=True)
    acc = {}

    def collect(spec, step, total):
        if step < total - 500:
            return
        with torch.no_grad():
            for i, p in enumerate(spec):
                G = p.grad
                acc[i] = acc.get(i, 0) + G @ G.mH  # (K, Cin, Cin)
                acc[("R", i)] = acc.get(("R", i), 0) + G.mH @ G

    res = train(dict(arm="adamw", lr=1e-3, seed=0, dataset="burgers"), collect)
    rows, condL, condR = [], [], []
    for i in range(len([k for k in acc if not isinstance(k, tuple)])):
        cL = eig_condition(acc[i]).cpu()
        cR = eig_condition(acc[("R", i)]).cpu()
        condL += cL.tolist()
        condR += cR.tolist()
        rows.append(f"| {i} | {cL.median():.3g} | {cL.min():.3g} | {cL.max():.3g} | {cR.median():.3g} |")
    med = statistics.median(condL)
    go = med > 10
    md = "\n".join([
        "## Experiment 3 kill test: conditioning of per-mode Shampoo factors (FNO-1D, Burgers, AdamW)", "",
        f"L_k = sum over the last 500 steps of G_k G_k^H (Cin x Cin, complex), per layer and kept mode. AdamW run rel. L2 test error {res['final']:.4g}.", "",
        "| layer | median cond(L_k) | min | max | median cond(R_k) |", "|---|---|---|---|---|", *rows, "",
        f"median cond(L_k) over all layers and modes = {med:.4g}",
        f"**Verdict: {'GO for the Shampoo variants' if go else 'Shampoo variants NO-GO; only Mode-Muon (and controls) go on'}** (threshold 10)."]) + "\n"
    open(os.path.join(d, "summary.md"), "w").write(md)
    json.dump(dict(go=go, median_cond=med), open(os.path.join(d, "results.json"), "w"))
    print(md)
    return go


def main(shampoo_go):
    names = [n for n in ARMS if shampoo_go or n not in SHAMPOO_ARMS]
    out_md = []
    for ds in ("burgers", "darcy", "ns"):
        d = os.path.join(OUT, "exp3_main", ds)
        arms = {n: dict(lr=ARMS[n][2], dataset=ds) for n in names}
        res = pool.sweep(os.path.abspath(__file__), arms, d, higher=False, timeout=1800)
        md, _ = pool.summarize(res, False, "rel. L2 error", f"Experiment 3 main: {ds}")
        out_md.append(md)
    md = "\n".join(out_md)
    os.makedirs(os.path.join(OUT, "exp3_main"), exist_ok=True)
    open(os.path.join(OUT, "exp3_main", "summary.md"), "w").write(md)
    print(md)


if __name__ == "__main__":
    cmd = sys.argv[1]
    if cmd == "job":
        job(json.loads(sys.argv[2]))
    elif cmd == "kill":
        kill()
    elif cmd == "main":
        main(json.load(open(os.path.join(OUT, "exp3_kill", "results.json")))["go"])
    elif cmd == "all":
        main(kill())
